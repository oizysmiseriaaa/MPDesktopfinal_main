export function normalizeUnitKey(value?: string | null) {
  return String(value || "")
    .trim()
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, "");
}

export function getMissingOfficialUnits(
  existingUnits: Array<{
    id?: string;
    name?: string;
    unitNumber?: string;
  }> = [],
) {
  const existingKeys = new Set(
    existingUnits
      .map((unit) => [unit?.name, unit?.unitNumber])
      .flat()
      .filter(Boolean)
      .map((value) => normalizeUnitKey(String(value))),
  );

  return OFFICIAL_UNITS.filter(
    (unit) => !existingKeys.has(normalizeUnitKey(unit.name)),
  );
}

export function mergeOfficialUnits(
  existingUnits: Array<Record<string, any>> = [],
) {
  const merged = [...existingUnits];
  const existingKeys = new Set(
    merged
      .map((unit) => [unit?.name, unit?.unitNumber, unit?.id])
      .flat()
      .filter(Boolean)
      .map((value) => normalizeUnitKey(String(value))),
  );

  OFFICIAL_UNITS.forEach((unit, index) => {
    const key = normalizeUnitKey(unit.name);
    if (existingKeys.has(key)) return;

    merged.push({
      id: `official-${index + 1}-${key}`,
      ...unit,
      name: unit.name,
      unitNumber: unit.unitNumber || unit.name,
      createdAt: new Date().toISOString(),
    });
  });

  return merged.sort((left, right) => {
    const leftLabel = String(left?.unitNumber || left?.name || left?.id || "");
    const rightLabel = String(
      right?.unitNumber || right?.name || right?.id || "",
    );
    return leftLabel.localeCompare(rightLabel);
  });
}
